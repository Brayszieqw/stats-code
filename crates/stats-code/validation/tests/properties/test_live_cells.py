"""Per-cell Live reference smoke tests (task 11.7).

Validates Requirements 4.3, 4.8.

For every ``(algorithm, software)`` cell in the Algorithm Coverage Matrix
whose value is ``live``, ensure that **at least one** Live test case can
exercise the Reference adapter end-to-end on a synthetic dataset
generated by ``hypothesis``.

Wave-1 interpretation of the task contract ("每个矩阵 live cell 至少一个
case"):

* The full Stats Engine ↔ Reference comparison for a curated dataset is
  already exercised by ``tests/properties/test_numerical_parity.py`` and
  by the orchestrator in ``run_validation.py``. Re-doing that loop here
  for every cell would add ~3 minutes to CI without improving signal.
* What was missing before this task: a hypothesis-driven generator that
  *also* wires up the per-cell Live Reference path (Python in-process or
  Rscript). This file fills that gap.

For each ``live`` cell we therefore:

1. Generate a small synthetic dataset (or spec) deterministically via
   ``hypothesis``. Generators are tight: numeric columns clamped into
   shapes the underlying reference function tolerates (no NaN, group
   imbalance ≥ 2, score column injectable for ROC, etc.).
2. Invoke the Reference adapter for that ``(algorithm, software)`` cell:
     * **Python column** → call the module's ``_python_reference`` /
       ``_ref_stats`` helper (or the matching ``ADAPTERS_FOR`` adapter
       for linear / logistic / cox / power / math_core), all of which
       are pure in-process scipy / statsmodels / lifelines / sklearn
       calls.
     * **R column** → probe ``RscriptAdapter.is_available()``. When
       Rscript is missing the case is short-circuited to a
       ``reference_software_unavailable`` skip per Requirement 4.9. When
       Rscript *is* available we invoke the existing ``RsurvivalAdapter``
       for cox / kaplan_meier; other R live cells (ttest, anova,
       nonparametric, correlation, or_rr, linear, logistic,
       power_single_arm, power_phase3, tableone, diagnostic_roc) have
       no Rscript adapter wired yet and are skipped with the
       ``live_R_adapter_not_yet_implemented`` reason — that gap is
       tracked in ``parity/adapters.py`` and lands in a follow-up wave.
3. Assert the Reference returns at least one finite numeric metric for
   the generated dataset.

Because hypothesis is run with a low ``max_examples`` here, the file
stays well under a second per cell and adds < 30 s of total CI time.
"""

