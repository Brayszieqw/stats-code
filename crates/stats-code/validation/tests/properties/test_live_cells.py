def _live_cells() -> list[tuple[str, str]]:
    """Return every ``(algorithm_id, software)`` cell whose matrix value is ``live``.

    The matrix is loaded fresh so that any ``coverage_matrix.toml`` change
    in the same PR is reflected without a reimport dance.
    """
    matrix = run_validation.load_coverage_matrix(_VALIDATION_DIR)
    cells: list[tuple[str, str]] = []
    for entry in matrix.get("algorithm", []):
        algorithm_id = str(entry["id"])
        coverage = entry.get("coverage", {})
        for software, value in coverage.items():
            if value == "live":
                cells.append((algorithm_id, software))
    return cells


_LIVE_CELLS = _live_cells()
_LIVE_CELL_IDS = [f"{alg}-{sw}" for alg, sw in _LIVE_CELLS]


# ---------------------------------------------------------------------------
# Hypothesis dataset generators
# ---------------------------------------------------------------------------
#
# The generator produces datasets that are simultaneously:
#
#   * *varied* — references like statsmodels / lifelines / scipy collapse to
#     ``KeyError('const')`` (no ``add_constant`` column when X is constant) or
#     ``ConvergenceError`` (Cox singular matrix) when every row is identical.
#     Hypothesis will aggressively shrink toward "all min" so we cannot rely
#     on iid float draws — we draw *unique* values per numeric column.
#   * *small but non-degenerate* — both binary outcomes (``disease`` /
#     ``death``) carry at least one of each class so logistic / OR-RR / ROC
#     don't degenerate to perfect separation; group is balanced so by-group
#     splits are non-empty for ttest / anova / nonparametric / KM / OR-RR.
#   * *signal-bearing* — ``linear_y`` is built from ``age + bmi`` plus a
#     small noise draw so OLS recovers a well-defined β; ``disease`` and
#     ``death`` are derived from ``age`` + a deterministic shuffle so the
#     binary outcomes are correlated enough to keep IRLS / Cox convergence
#     out of the degenerate regime without making any single test trivial.

_DATASET_N = 30
_HALF_N = _DATASET_N // 2

# n distinct floats per numeric column — forces variance.
_AGE_STRAT = st.lists(
    st.floats(min_value=18.0, max_value=90.0, allow_nan=False, allow_infinity=False),
    min_size=_DATASET_N, max_size=_DATASET_N, unique=True,
)
_BMI_STRAT = st.lists(
    st.floats(min_value=15.0, max_value=45.0, allow_nan=False, allow_infinity=False),
    min_size=_DATASET_N, max_size=_DATASET_N, unique=True,
)
_TIME_STRAT = st.lists(
    st.floats(min_value=0.05, max_value=10.0, allow_nan=False, allow_infinity=False),
    min_size=_DATASET_N, max_size=_DATASET_N, unique=True,
)
# Small noise on the outcome so the linear model doesn't fit perfectly (which
# also yields a t-statistic of ±inf and an undefined p-value).
_NOISE_STRAT = st.lists(
    st.floats(min_value=-3.0, max_value=3.0, allow_nan=False, allow_infinity=False),
    min_size=_DATASET_N, max_size=_DATASET_N,
)
# A permutation seed used to reorder which half of the rows carries
# disease=1 / death=1 — keeps both binary outcomes balanced (15/15) while
# letting hypothesis vary which rows are positive.
_PERM_STRAT = st.lists(
    st.integers(min_value=0, max_value=10_000),
    min_size=_DATASET_N, max_size=_DATASET_N,
)


def _stratified_binary(perm: list[int]) -> list[int]:
    """Binary vector with **all four 2x2 cells non-empty** vs ``group``.

    Group is the deterministic ``[0]*15 + [1]*15`` vector built in
    :func:`_balanced_dataset`. Within each group we promote a
    perm-controlled subset to value 1 so the four-corner counts of the
    contingency table ``(disease ∈ {0, 1}) × (group ∈ {0, 1})`` are all
    strictly positive — without that, ``parity.or_rr._python_reference``
    yields ``NaN`` for every metric and the live cell signal is lost.

    Layout: 5 positives in group 0, 9 positives in group 1 →
    a=9, b=6, c=5, d=10. None equals zero, so OR / RR and their Woolf /
    log-method CIs are all defined.
    """
    out = [0] * _DATASET_N
    g0_indices = list(range(_HALF_N))
    g1_indices = list(range(_HALF_N, _DATASET_N))
    g0_indices.sort(key=lambda i: (perm[i], i))
    g1_indices.sort(key=lambda i: (perm[i], i))
    for i in g0_indices[:5]:
        out[i] = 1
    for i in g1_indices[:9]:
        out[i] = 1
    return out


@st.composite
def _balanced_dataset(draw, *, n: int = _DATASET_N):
    """Generate a balanced, non-degenerate dataset with the columns the parity
    collectors expect by default: ``age, bmi, linear_y, disease, time, death,
    group``.

    Properties guaranteed for every drawn instance (and therefore for every
    counter-example hypothesis would otherwise shrink to):

    * 30 rows, 15 per ``group`` value, 15 per ``disease`` value, 15 per
      ``death`` value.
    * ``age``, ``bmi``, ``time`` are 30 distinct floats inside their nominal
      clinical ranges.
    * ``linear_y`` ≈ ``0.5 * age + 0.3 * bmi + noise`` so OLS / scipy
      pearsonr have signal to recover.
    """
    assert n == _DATASET_N, (
        "_balanced_dataset is calibrated for n=30; rebuild the strategies "
        "above to vary the sample size."
    )

    age = draw(_AGE_STRAT)
    bmi = draw(_BMI_STRAT)
    time = draw(_TIME_STRAT)
    noise = draw(_NOISE_STRAT)
    disease_perm = draw(_PERM_STRAT)
    death_perm = draw(_PERM_STRAT)

    disease = _stratified_binary(disease_perm)
    death = _stratified_binary(death_perm)

    rows: list[dict[str, Any]] = []
    for i in range(n):
        rows.append({
            "age": age[i],
            "bmi": bmi[i],
            "linear_y": 0.5 * age[i] + 0.3 * bmi[i] + noise[i],
            "disease": disease[i],
            "time": time[i],
            "death": death[i],
            "group": 0 if i < _HALF_N else 1,
        })
    return rows


def _write_csv(tmp_path: Path, rows: list[dict[str, Any]]) -> Path:
    """Write *rows* to ``<tmp_path>/synth.csv`` and return the path."""
    out = tmp_path / "synth.csv"
    fieldnames = list(rows[0].keys())
    with out.open("w", encoding="utf-8", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=fieldnames, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    return out


# ---------------------------------------------------------------------------
# Reference invokers — one per algorithm
# ---------------------------------------------------------------------------
#
# Each callable returns a ``dict[str, float]`` of metrics produced by the
# Reference adapter for the supplied dataset / spec. The test asserts at
# least one finite metric is present.
#
# Several algorithms have a module-level ``_python_reference`` helper that
# already wraps the Reference engine. Where the module instead delegates to
# ``ADAPTERS_FOR``, we invoke the matching adapter directly so this file
# stays decoupled from the orchestrator.

def _ref_linear(dataset: Path) -> dict[str, float]:
    from parity.adapters import StatsmodelsAdapter
    return StatsmodelsAdapter().fit("linear", dataset, {
        "outcome": "linear_y",
        "covariates": ["age", "bmi"],
    })


def _ref_logistic(dataset: Path) -> dict[str, float]:
    from parity.adapters import StatsmodelsAdapter
    return StatsmodelsAdapter().fit("logistic", dataset, {
        "outcome": "disease",
        "covariates": ["age", "bmi"],
    })


def _ref_cox_python(dataset: Path) -> dict[str, float]:
    from parity.adapters import LifelinesAdapter
    return LifelinesAdapter().fit("cox", dataset, {
        "duration_col": "time",
        "event_col": "death",
        "covariates": ["age", "bmi"],
    })


def _ref_cox_r(dataset: Path) -> dict[str, float]:
    return RsurvivalAdapter().fit("cox", dataset, {
        "duration_col": "time",
        "event_col": "death",
        "covariates": ["age", "bmi"],
    })


def _ref_kaplan_meier_python(dataset: Path) -> dict[str, float]:
    from parity.kaplan_meier import _python_reference
    return _python_reference(dataset, {
        "duration_col": "time",
        "event_col": "death",
        "group_col": "group",
    })


def _ref_kaplan_meier_r(dataset: Path) -> dict[str, float]:
    return RsurvivalAdapter().fit("km", dataset, {
        "duration_col": "time",
        "event_col": "death",
    })


def _ref_ttest(dataset: Path) -> dict[str, float]:
    from parity.ttest import _python_reference
    return _python_reference(dataset, {"by": "group", "var": "age"})


def _ref_anova(dataset: Path) -> dict[str, float]:
    from parity.anova import _python_reference
    return _python_reference(dataset, {"by": "group", "var": "age"})


def _ref_nonparametric(dataset: Path) -> dict[str, float]:
    from parity.nonparametric import _python_reference
    return _python_reference(dataset, {"by": "group", "var": "age", "test": "mann_whitney"})


def _ref_correlation(dataset: Path) -> dict[str, float]:
    from parity.correlation import _python_reference
    return _python_reference(dataset, {"x": "age", "y": "bmi", "method": "pearson"})


def _ref_or_rr(dataset: Path) -> dict[str, float]:
    from parity.or_rr import _python_reference
    return _python_reference(dataset, {"exposure": "group", "outcome": "disease"})


def _ref_tableone(dataset: Path) -> dict[str, float]:
    import pandas as pd  # local — only the live cells need the library

    from parity.tableone import _ref_stats
    df = pd.read_csv(dataset)
    return _ref_stats(df, var="age", by="group")


def _ref_diagnostic_roc(dataset: Path) -> dict[str, float]:
    """Build a deterministic score column then call sklearn through SklearnAdapter.

    ``parity/diagnostic_roc.py`` injects a logistic-regression score column
    on the fly; we reproduce that idea here without writing to disk a
    second time, so the synthetic dataset path stays the single source of
    truth for the case.
    """
    import pandas as pd

    from parity.adapters import SklearnAdapter

    df = pd.read_csv(dataset)
    # Produce a monotone-with-disease score so AUC is well-defined.
    df["score"] = (df["age"] / 100.0) + 0.1 * df["disease"]
    enriched = dataset.with_name("synth_with_score.csv")
    df.to_csv(enriched, index=False)
    return SklearnAdapter().fit("diagnostic_roc", enriched, {
        "label_col": "disease",
        "score_col": "score",
        "threshold": 0.5,
    })
def _ref_power_single_arm(_dataset: Path) -> dict[str, float]:
    """``power_single_arm`` is a dataset-free algorithm; we feed the spec only."""
    from parity.power_single_arm import _python_reference
    return _python_reference({
        "p0": 0.20,
        "p1": 0.35,
        "alpha": 0.05,
        "power": 0.80,
    })


def _ref_power_phase3(_dataset: Path) -> dict[str, float]:
    """``power_phase3`` collector is a wave-1 stub; the real Live reference
    is statsmodels' ``TTestIndPower``. Calling it directly here so the
    cell still has at least one Live case wired up via hypothesis."""
    from statsmodels.stats.power import TTestIndPower
    analysis = TTestIndPower()
    n = analysis.solve_power(effect_size=0.5, alpha=0.05, power=0.80)
    return {
        "required_n": float(n),
        "achieved_power": float(analysis.solve_power(effect_size=0.5, alpha=0.05, nobs1=n)),
    }


