def _has_finite(values: Iterable[Any]) -> bool:
    """At least one numeric value in *values* is finite."""
    for v in values:
        try:
            if math.isfinite(float(v)):
                return True
        except (TypeError, ValueError):
            continue
    return False


def _hypothesis_settings() -> settings:
    """Tight settings: per-cell budget is small, generators are deterministic.

    A few ``max_examples`` are enough — the goal is to wire one Live case
    through hypothesis per cell, not to exhaustively explore the input
    space; the orchestrator's ``run_validation.py`` already covers that on
    the curated synthetic / public datasets.
    """
    return settings(
        max_examples=2,
        deadline=None,
        suppress_health_check=[
            HealthCheck.function_scoped_fixture,
            HealthCheck.too_slow,
        ],
    )


