@pytest.mark.parametrize(("algorithm_id", "software"), _LIVE_CELLS, ids=_LIVE_CELL_IDS)
def test_live_cell_has_at_least_one_case(
    algorithm_id: str,
    software: str,
    tmp_path: Path,
) -> None:
    """Every ``live`` cell drives the Reference adapter on a hypothesis dataset.

    Validates Requirements 4.3, 4.8.
    """
    if software == "Python":
        invoker = _PYTHON_LIVE_REFS.get(algorithm_id)
        if invoker is None:
            pytest.fail(
                f"live cell ({algorithm_id}, Python) has no Live reference "
                f"invoker wired in test_live_cells.py — see _PYTHON_LIVE_REFS"
            )
    elif software == "R":
        if not RscriptAdapter().is_available():
            pytest.skip("reference_software_unavailable: Rscript not on PATH")
        invoker = _R_LIVE_REFS.get(algorithm_id)
        if invoker is None:
            pytest.skip(
                "live_R_adapter_not_yet_implemented: "
                f"no Rscript adapter for ({algorithm_id}, R) in parity/adapters.py"
            )
    else:
        pytest.fail(f"unexpected live software for the live arm: {software!r}")

    # Use a short-lived directory so successive hypothesis runs don't pile up
    # in the parametrized tmp_path.
    cell_dir = tmp_path / f"{algorithm_id}__{software}"
    cell_dir.mkdir(parents=True, exist_ok=True)

    @given(rows=_balanced_dataset(n=30))
    @_hypothesis_settings()
    def _run(rows: list[dict[str, Any]]) -> None:
        # Wipe the previous example's CSV(s) so diagnostic_roc's enriched
        # file doesn't pile up across hypothesis examples.
        for stale in cell_dir.glob("*.csv"):
            stale.unlink()
        dataset = _write_csv(cell_dir, rows)
        metrics = invoker(dataset)
        assert isinstance(metrics, dict) and metrics, (
            f"Live reference for ({algorithm_id}, {software}) returned no "
            f"metrics on the hypothesis-generated dataset at {dataset}"
        )
        assert _has_finite(metrics.values()), (
            f"Live reference for ({algorithm_id}, {software}) returned no "
            f"finite metric on {dataset}: {metrics!r}"
        )

    _run()


def test_live_cells_inventory_is_non_empty() -> None:
    """Sanity check: the matrix must declare at least one ``live`` cell.

    If a future PR accidentally drops every ``live`` cell, the
    parametrized test above would silently pass with zero invocations and
    Requirements 4.3 / 4.8 would lose their guard. This zero-coverage
    canary catches that regression.
    """
    assert _LIVE_CELLS, (
        "coverage_matrix.toml has no `live` cells — Requirements 4.3 / 4.8 "
        "demand at least one Live test case for R / Python live coverage."
    )
