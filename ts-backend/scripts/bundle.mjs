// scripts/bundle.mjs — esbuild single-file CommonJS bundle (Phase 0, task 1.3).
//
// Produces build/bundle.cjs: one self-contained CommonJS file that the Node SEA
// blob mechanism can embed. The bundle is the engine bin entry plus everything
// it transitively imports. The application version is inlined via `define` so
// the packaged .exe performs no package.json read.

import { build } from 'esbuild';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { mkdirSync } from 'node:fs';

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');

const enginePkg = require(resolve(root, 'packages/engine/package.json'));
const version = enginePkg.version ?? '0.0.0';

const outdir = resolve(root, 'build');
mkdirSync(outdir, { recursive: true });
const outfile = resolve(outdir, 'bundle.cjs');

await build({
  entryPoints: [resolve(root, 'packages/engine/dist/bin.js')],
  bundle: true,
  platform: 'node',
  target: 'node22',
  format: 'cjs',
  outfile,
  // Native FFI (koffi, task 3.7) cannot be embedded; mark external so it is
  // resolved from a sibling folder at runtime, with a graceful fallback.
  external: ['koffi'],
  define: {
    __STATS_CODE_VERSION__: JSON.stringify(version),
  },
  banner: {
    js: '// stats-code SEA bundle — generated by scripts/bundle.mjs. Do not edit.',
  },
  legalComments: 'none',
  minify: false,
  sourcemap: false,
});

console.log(`bundled → ${outfile} (version ${version})`);
